"""Finds candidate example lines for the paper's qualitative table (review
item T4): reference lines of moderate length where the raw Tesseract output
has word errors, scored by what the main methods did to the matching span.

For each reference line, the best-matching span of each output page is found
with a fuzzy partial alignment, then compared word by word. Prints the top
candidates of two kinds: a word fixed by Qwen3 1.7B (its WER gain on
Tesseract text), and a line regenerated by a Bengali-specific model.

Usage:
    python find_examples.py --ocr-path ../results/ocr_eval40.jsonl \\
        --correction-path ../results/eval40_ocr.jsonl
"""
import argparse
import json
from pathlib import Path

from rapidfuzz import fuzz

from metrics import cer, normalize

import sys
sys.stdout.reconfigure(encoding="utf-8", errors="replace")


def best_span(line: str, page: str) -> str:
    """The substring of page that best matches line, widened to whole words."""
    page = normalize(page)
    al = fuzz.partial_ratio_alignment(line, page)
    start, end = al.dest_start, al.dest_end
    while start > 0 and page[start - 1] != " ":
        start -= 1
    while end < len(page) and page[end] != " ":
        end += 1
    return page[start:end]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--ocr-path", type=Path, required=True)
    parser.add_argument("--correction-path", type=Path, required=True)
    args = parser.parse_args()

    pages = {json.loads(l)["page_id"]: json.loads(l) for l in
             args.ocr_path.read_text(encoding="utf-8").splitlines() if l.strip()}
    out = {}
    for l in args.correction_path.read_text(encoding="utf-8").splitlines():
        if l.strip():
            r = json.loads(l)
            out[(r["engine"], r["model_key"], r["page_id"])] = r["raw_output"]

    fixed, regen = [], []
    for pid, p in pages.items():
        for line in p["ground_truth"].split("\n"):
            line = normalize(line)
            if not 25 <= len(line) <= 60:
                continue
            gt_words = line.split()
            tess = best_span(line, p["tesseract"])
            if cer(line, tess) > 0.35 or cer(line, tess) < 0.05:
                continue
            qwen = best_span(line, out[("tesseract", "qwen3-1.7b", pid)])
            tess_ok = sum(w in gt_words for w in tess.split())
            qwen_ok = sum(w in gt_words for w in qwen.split())
            if qwen_ok > tess_ok and cer(line, qwen) < cer(line, tess):
                fixed.append((cer(line, tess) - cer(line, qwen), pid, line))
            titu = best_span(line, out[("tesseract", "titullm-3b-instruct", pid)])
            gemma = best_span(line, out[("tesseract", "gemma-2b", pid)])
            if cer(line, titu) > 0.6 and cer(line, gemma) <= cer(line, tess) + 0.02:
                regen.append((cer(line, titu), pid, line))

    for name, items in [("Qwen3 fixes words", fixed), ("Bengali model regenerates", regen)]:
        print(f"== {name}: {len(items)} candidates")
        for score, pid, line in sorted(items, reverse=True)[:6]:
            print(f"  {score:.2f}  {pid}  {line}")


if __name__ == "__main__":
    main()
