"""Builds the final paper as ONE self-contained LaTeX file, for Overleaf and for
sending to the reviewer: every \\input{tables/...} is inlined and the
bibliography is replaced by the compiled reference list (main.bbl), so
references.bib is not needed. Only the figures, the Bengali font and the
pre-rendered example table (for pdfLaTeX) stay separate files, because they
are not text.

Writes:
  paper/main-single.tex        the single file (committed)
  paper/overleaf-final.zip     main.tex (= main-single.tex) + figures/ + fonts/
                               + tables/examples_body.pdf (gitignored)

Compile on Overleaf with XeLaTeX (Menu > Compiler) for the live Bengali
table; under pdfLaTeX the table comes from tables/examples_body.pdf.

Usage (from the repository root; needs Tectonic for the .bbl):
    python paper/scripts/make_single_file.py
"""
import re
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1]
INPUT = re.compile(r"\\input\{([^}]+)\}")


def inline(text, depth=0):
    if depth > 5:
        raise RuntimeError("\\input nested too deeply")

    def repl(m):
        name = m.group(1)
        path = PAPER / (name if name.endswith(".tex") else name + ".tex")
        body = path.read_text(encoding="utf-8").rstrip("\n")
        return "% ---- begin " + name + " ----\n" + inline(body, depth + 1) + "\n% ---- end " + name + " ----"

    out = []
    for line in text.split("\n"):
        # Leave \input inside a comment alone (preamble.tex mentions one in its first line).
        comment = re.search(r"(?<!\\)%", line)
        code, rest = (line[:comment.start()], line[comment.start():]) if comment else (line, "")
        out.append(INPUT.sub(repl, code) + rest)
    return "\n".join(out)


def compiled_bbl():
    with tempfile.TemporaryDirectory() as tmp:
        r = subprocess.run(["tectonic", "-X", "compile", "main.tex", "--keep-intermediates", "--outdir", tmp],
                           cwd=PAPER, capture_output=True, text=True)
        bbl = Path(tmp) / "main.bbl"
        if r.returncode != 0 or not bbl.exists():
            sys.exit("Tectonic failed:\n" + r.stdout[-2000:] + r.stderr[-2000:])
        return bbl.read_text(encoding="utf-8").rstrip("\n")


def main():
    tex = (PAPER / "main.tex").read_text(encoding="utf-8")
    tex = inline(tex)
    bib = re.compile(r"\\bibliographystyle\{IEEEtran\}\s*\n\\bibliography\{references\}")
    if not bib.search(tex):
        sys.exit("bibliography commands not found in main.tex")
    bbl = compiled_bbl()
    tex = bib.sub(lambda m: "% ---- bibliography (compiled from references.bib with IEEEtran.bst) ----\n" + bbl, tex)
    header = ("% Single-file version of the paper, generated by paper/scripts/make_single_file.py\n"
              "% from main.tex, tables/*.tex and references.bib. Do not edit by hand: edit those and rerun.\n")
    out = PAPER / "main-single.tex"
    out.write_text(header + tex + ("\n" if not tex.endswith("\n") else ""), encoding="utf-8")
    left = [l for l in tex.split("\n") if INPUT.search(l.split("%")[0])]
    print(f"Wrote {out} ({len(tex.splitlines())} lines); remaining \\input: {left or 'none'}")

    figures = sorted(set(re.findall(r"\\includegraphics(?:\[[^]]*\])?\{([^}]+)\}", tex)))
    zpath = PAPER / "overleaf-final.zip"
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        z.write(out, "main.tex")
        for f in figures:
            z.write(PAPER / f, f)
        for font in sorted((PAPER / "fonts").glob("*")):
            z.write(font, f"fonts/{font.name}")
    print(f"Wrote {zpath}: main.tex + {len(figures)} figure files + fonts")


if __name__ == "__main__":
    main()
